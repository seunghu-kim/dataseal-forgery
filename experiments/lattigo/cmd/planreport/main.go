// Command planreport emits the deterministic G7 capacity/packing feasibility
// matrix from the bfvpack planner. It writes machine-readable JSON and a
// human-readable Markdown table; no numbers are hand-coded.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"dsfgo/bfvpack"
)

type row struct {
	Config       string             `json:"config"`
	ChecksumRows int                `json:"checksum_rows"`
	N            int                `json:"n"`
	Plan         bfvpack.MatmulPlan `json:"plan"`
}

func main() {
	jsonOut := "../../results/lattigo/final/feasibility.json"
	mdOut := "../../docs/lattigo_128_feasibility.md"
	if len(os.Args) == 3 {
		jsonOut, mdOut = os.Args[1], os.Args[2]
	}
	os.MkdirAll(dir(jsonOut), 0o755)
	os.MkdirAll(dir(mdOut), 0o755)

	sizes := []int{8, 16, 32, 64, 128}
	// scheme -> checksum rows appended to the confidential operand before matmul.
	configs := []struct {
		name     string
		checksum int
	}{
		{"bfv_only", 0},
		{"dataseal_original", 2},
		{"dataseal_strengthened", 2},
		{"private_sketch", 0},
	}
	const tile = 64
	const base = "PN14QP438"

	var rows []row
	for _, cfg := range configs {
		for _, n := range sizes {
			p := bfvpack.PlanMatmul(cfg.name, n, n, n, cfg.checksum, tile, base)
			rows = append(rows, row{cfg.name, cfg.checksum, n, p})
		}
	}
	// rectangular cases.
	rects := [][3]int{{32, 64, 32}, {64, 128, 64}}
	for _, cfg := range configs {
		for _, r := range rects {
			p := bfvpack.PlanMatmul(cfg.name, r[0], r[1], r[2], cfg.checksum, tile, base)
			rows = append(rows, row{cfg.name + "_rect", cfg.checksum, r[0], p})
		}
	}

	writeJSON(jsonOut, map[string]interface{}{
		"base_param": base, "tile_size": tile, "params": bfvpack.Params, "rows": rows,
	})
	os.WriteFile(mdOut, []byte(renderMarkdown(base, tile, rows)), 0o644)
	fmt.Println("wrote", jsonOut, "and", mdOut)
}

func renderMarkdown(base string, tile int, rows []row) string {
	var b strings.Builder
	b.WriteString("# Lattigo/BFV 128 Feasibility & Capacity Plan (G7)\n\n")
	b.WriteString("Deterministically generated by `cmd/planreport` from `bfvpack.PlanMatmul`; ")
	b.WriteString("validated by `bfvpack/plan_test.go` and round-trip `tiled_test.go`.\n\n")
	b.WriteString(fmt.Sprintf("Base comparison parameter group: **%s** (t=65537). Tile size T=**%d**. ", base, tile))
	b.WriteString("RowSlots = N/2 because BFV RotateColumns is cyclic within each N/2 half; all row-major data stays in the first half.\n\n")

	b.WriteString("## Parameter registry\n\n| name | logN | N | RowSlots (N/2) |\n|---|---|---|---|\n")
	for _, p := range bfvpack.Params {
		b.WriteString(fmt.Sprintf("| %s | %d | %d | %d |\n", p.Name, p.LogN, p.N, p.RowSlots))
	}
	b.WriteString("\nPN16 is intentionally excluded: it is not a pinned default and is not silently introduced.\n\n")

	b.WriteString("## Public-right matmul per configuration\n\n")
	b.WriteString("Columns: logical (n,d,ell); checksum rows; single-ct square dim and slots; smallest registry param holding one ciphertext; whether one ciphertext fits the base group; chosen strategy at base; tile grid IxKxJ with multiplies/adds.\n\n")
	b.WriteString("| config | n,d,ell | chk | single-ct dim | single-ct slots | single-ct param | strategy@base | tile IxKxJ | mul/add | reason |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		p := r.Plan
		scp := p.SingleCtParam
		if scp == "" {
			scp = "none"
		}
		b.WriteString(fmt.Sprintf("| %s | %d,%d,%d | %d | %d | %d | %s | %s | %dx%dx%d | %d/%d | %s |\n",
			r.Config, p.N, p.D, p.Ell, p.ChecksumRows, p.SingleCtDim, p.SingleCtSlots, scp,
			p.Strategy, p.IBlocks, p.KBlocks, p.JBlocks, p.TileMultiplies, p.TileAdds, p.Reason))
	}

	b.WriteString("\n## 128 boundary summary\n\n")
	b.WriteString("- **bfv_only / private_sketch (no checksum rows), 128x128:** 128^2 = 16384 logical values = whole PN14 ciphertext (both halves); exceeds one PN14 half (8192). Single ciphertext needs **PN15** (128^2 = 16384 = PN15 half), validated by `TestSingleCtPN15_128`. The uniform implemented path tiles at PN14 (2x2x2) to keep one comparison group.\n")
	b.WriteString("- **DataSeal 128x128:** two checksum rows make the confidential operand 130x128 -> square dim 130, 16900 slots > PN15 half (16384). **No single ciphertext in the registry.** Implemented via honest tiling at PN14: 3 block rows (64,64,2) x 2 x 2.\n")
	b.WriteString("- Tiling reuses the verified single-ciphertext `PublicRightMatmul` kernel per block plus ciphertext-ciphertext adds; correctness is covered for 8,130,128,rectangular, and sub-tile shapes in `tiled_test.go`.\n")
	b.WriteString("- VERITAS REP/PE reduce logical slots to N/NumReplications (REP) or expand ciphertext components (PE); their 128 capacity is accounted separately in the comparability matrix and G8 notes.\n")
	return b.String()
}

func dir(p string) string {
	i := strings.LastIndex(p, "/")
	if i < 0 {
		return "."
	}
	return p[:i]
}

func writeJSON(path string, v interface{}) {
	b, _ := json.MarshalIndent(v, "", "  ")
	os.WriteFile(path, b, 0o644)
}
